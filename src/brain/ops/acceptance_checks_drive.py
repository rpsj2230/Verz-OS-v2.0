"""The install acceptance check for Google Drive: a folder connected, indexed and read, no socket.

`brain.ops.acceptance_checks_google` proves a Google source whose values are figures. A Drive folder
is the other shape: its index is the folder's files, and what a question is answered from is a
file's words, read from Drive while the asker waits and handed to the model step as a passage. So
this check connects a folder made up for the run inside the check's transaction through the store
the Connectors screen's routes call, lets the worker's own `brain.ops.connector_sync_run.attempt`
list it into the index with a token a generated key file bought, and then asks the application's
own passage reader (`brain.ops.drive_passages.DrivePassages`) over the index it wrote.

**No socket is opened and no real key is held.** Google's token endpoint and the Drive API are one
recorded caller answering in the documented envelopes and noting what it was asked. The key file is
generated by the check, signs a real assertion that nobody receives, and is dropped with the check.
See `brain.ops.acceptance_checks_connectors.A_RECORDED_ANSWER_IS_NEVER_A_CALL`.

**The words are a canary, so being read live and being kept nowhere are one observation each.**
The Google Doc's exported text carries a word minted for the run. It is told to the reader granted
the folder's files in the folder's department, only after Drive was asked for it, and afterwards
the install's index audit finds it in no table.

**Absent and denied are compared as the person sees them.** A reader without the grant, and a
reader holding it in the other department, are each handed exactly what a question about a file
that is not there hands them, and Drive is asked nothing for either.

**The tree is walked, and a file locked narrower than its folder is never read.** The Doc sits in
a subfolder, so the worker lists the pin and then the subfolder, and the Doc is read through the
subfolder the walk kept. A second file is listed with its folder's sharing and has its inherited
permissions switched off since: a question naming it has its metadata read, and its words are
never asked for
(`brain.connectors.google_drive.A_FILE_LOCKED_NARROWER_THAN_ITS_FOLDER_IS_NEVER_READ`).

**A tree wider and deeper than one pass is read whole over two, depth first (M11.9.15).** The
second check's pin holds three subfolders, the first of them a chain as deep as a pass has pages,
so the first pass stops inside that chain with the other two waiting on the path it saves. The
next pass starts at the page the first did not ask, not at the pin, finishes the chain and then
the two that waited, and leaves no place behind; every file is in the index once
(`brain.connectors.google_drive.A_WALK_S_PLACE_IS_ITS_PATH_AND_NOT_ITS_QUEUE`).

**The check steps aside where the install has Google Drive connected.** Connecting a source that
is connected already is refused, for `A_CONNECTED_SOURCE_IS_NOT_CONNECTED_AGAIN`'s reason.

Task ids: M11.6.7, M11.9.15
"""

